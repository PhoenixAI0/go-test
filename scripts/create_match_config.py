#!/usr/bin/env python3
"""Generate KataGo match configuration file for Elo evaluation.

This script creates a match config that can be used with eval_elo.py to
evaluate a trained model against KataGo.
"""

from __future__ import annotations

import argparse
import os
import sys
from venv_utils import ensure_virtualenv


def create_match_config(
    output_path: str,
    board_size: int,
    num_games: int,
    model_command: str,
    katago_bin: str,
    katago_model: str,
    katago_config: str,
    sgf_output_dir: str = "match_sgfs",
    main_time: int = 60,
    byoyomi_time: int = 5,
    byoyomi_periods: int = 5,
    komi: float = 7.5,
    rules: str = "chinese",
    model_name: str = "TrainedModel",
    katago_name: str = "KataGoBaseline",
) -> None:
    """Generate a KataGo match configuration file.

    Args:
        output_path: Path to write the config file
        board_size: Board size (9 or 19)
        num_games: Number of games to play
        model_command: Command to run trained model as GTP engine
        katago_bin: Path to KataGo binary
        katago_model: Path to KataGo model file
        katago_config: Path to KataGo analysis config
        sgf_output_dir: Directory to write SGF files
        main_time: Main time per player in seconds
        byoyomi_time: Byo-yomi time per move in seconds
        byoyomi_periods: Number of byo-yomi periods
        komi: Komi value
        rules: Rule set to use
        model_name: Display name for trained model
        katago_name: Display name for KataGo baseline
    """
    # Validate inputs
    if board_size not in (9, 19):
        raise ValueError("board_size must be 9 or 19")
    if num_games < 1:
        raise ValueError("num_games must be positive")

    # Expand paths
    katago_bin = os.path.expanduser(os.path.expandvars(katago_bin))
    katago_model = os.path.expanduser(os.path.expandvars(katago_model))
    katago_config = os.path.expanduser(os.path.expandvars(katago_config))
    model_command = os.path.expanduser(os.path.expandvars(model_command))

    # Build KataGo GTP command
    katago_command = f"{katago_bin} gtp -model {katago_model} -config {katago_config}"

    config_content = f"""# KataGo Match Configuration for {board_size}x{board_size} Go
# Generated by create_match_config.py

# Number of games to play
numGamesTotal = {num_games}

# Board configuration
boardSize = {board_size}
komi = {komi}
rules = {rules}

# Time controls (in seconds)
mainTime = {main_time}
byoYomiTime = {byoyomi_time}
byoYomiPeriods = {byoyomi_periods}

# SGF output settings
sgfOutputDir = {sgf_output_dir}/
writeSgf = true

# Match format
alternateColors = true

# Logging
logAllGTPCommunication = true
logSearchInfo = false

# Players
players = player1,player2

# Bot 1: Trained Model
player1 = {{
  name = {model_name}
  command = {model_command}
  trustPV = false
}}

# Bot 2: KataGo Baseline
player2 = {{
  name = {katago_name}
  command = {katago_command}
  trustPV = true
}}
"""

    # Write config file
    output_dir = os.path.dirname(output_path)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(config_content)

    print(f"Match config written to: {output_path}")
    print(f"  Board size: {board_size}x{board_size}")
    print(f"  Number of games: {num_games}")
    print(f"  SGF output: {sgf_output_dir}/")
    print(f"\nTo run the match:")
    print(f"  uv run python scripts/eval_elo.py --katago-bin {katago_bin} --match-config {output_path}")


def main() -> None:
    ensure_virtualenv()
    parser = argparse.ArgumentParser(
        description="Generate KataGo match configuration for Elo evaluation"
    )
    parser.add_argument(
        "--output",
        "-o",
        required=True,
        help="Path to write match config file",
    )
    parser.add_argument(
        "--board-size",
        type=int,
        default=9,
        choices=[9, 19],
        help="Board size (9 or 19, default: 9)",
    )
    parser.add_argument(
        "--num-games",
        type=int,
        default=200,
        help="Number of games to play (default: 200)",
    )
    parser.add_argument(
        "--model-command",
        required=True,
        help="Command to run your trained model as GTP engine",
    )
    parser.add_argument(
        "--katago-bin",
        default="${KATAGO_BIN}",
        help="Path to KataGo binary (default: ${KATAGO_BIN})",
    )
    parser.add_argument(
        "--katago-model",
        default="${KATAGO_MODEL}",
        help="Path to KataGo model (default: ${KATAGO_MODEL})",
    )
    parser.add_argument(
        "--katago-config",
        default="${KATAGO_CONFIG}",
        help="Path to KataGo analysis config (default: ${KATAGO_CONFIG})",
    )
    parser.add_argument(
        "--sgf-output-dir",
        default="match_sgfs",
        help="Directory for SGF output (default: match_sgfs)",
    )
    parser.add_argument(
        "--main-time",
        type=int,
        default=None,
        help="Main time in seconds (default: 60 for 9x9, 300 for 19x19)",
    )
    parser.add_argument(
        "--byoyomi-time",
        type=int,
        default=None,
        help="Byo-yomi time per move (default: 5 for 9x9, 10 for 19x19)",
    )
    parser.add_argument(
        "--byoyomi-periods",
        type=int,
        default=5,
        help="Number of byo-yomi periods (default: 5)",
    )
    parser.add_argument(
        "--komi",
        type=float,
        default=7.5,
        help="Komi value (default: 7.5)",
    )
    parser.add_argument(
        "--rules",
        default="chinese",
        help="Rule set to use (default: chinese)",
    )
    parser.add_argument(
        "--model-name",
        default="TrainedModel",
        help="Display name for trained model (default: TrainedModel)",
    )
    parser.add_argument(
        "--katago-name",
        default="KataGoBaseline",
        help="Display name for KataGo (default: KataGoBaseline)",
    )

    args = parser.parse_args()

    # Set default time controls based on board size
    if args.main_time is None:
        args.main_time = 60 if args.board_size == 9 else 300
    if args.byoyomi_time is None:
        args.byoyomi_time = 5 if args.board_size == 9 else 10

    try:
        create_match_config(
            output_path=args.output,
            board_size=args.board_size,
            num_games=args.num_games,
            model_command=args.model_command,
            katago_bin=args.katago_bin,
            katago_model=args.katago_model,
            katago_config=args.katago_config,
            sgf_output_dir=args.sgf_output_dir,
            main_time=args.main_time,
            byoyomi_time=args.byoyomi_time,
            byoyomi_periods=args.byoyomi_periods,
            komi=args.komi,
            rules=args.rules,
            model_name=args.model_name,
            katago_name=args.katago_name,
        )
    except ValueError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
