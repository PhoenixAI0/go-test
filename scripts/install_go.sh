#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

# Default Go version. Override with GO_VERSION=1.xx.x ./scripts/install_go.sh
GO_VERSION="${GO_VERSION:-1.22.5}"

OS="$(uname -s | tr '[:upper:]' '[:lower:]')"
ARCH="$(uname -m)"

if [[ "$OS" != "linux" ]]; then
    echo "Go auto-install is only supported on Linux in this script."
    echo "Please install Go manually: https://go.dev/dl/"
    exit 1
fi

case "$ARCH" in
    x86_64) GO_ARCH="amd64" ;;
    aarch64|arm64) GO_ARCH="arm64" ;;
    *)
        echo "Unsupported architecture: $ARCH"
        echo "Please install Go manually: https://go.dev/dl/"
        exit 1
        ;;
esac

if command -v go &>/dev/null; then
    echo "Go is already installed: $(go version)"
    exit 0
fi

INSTALL_DIR="$HOME/.local/go"
ARCHIVE="go${GO_VERSION}.${OS}-${GO_ARCH}.tar.gz"
URL="https://go.dev/dl/${ARCHIVE}"
TMP_DIR="${TMPDIR:-/tmp}"
ARCHIVE_PATH="${TMP_DIR}/${ARCHIVE}"

echo "Installing Go ${GO_VERSION} to ${INSTALL_DIR}..."
echo "Downloading: ${URL}"

curl -fsSL "${URL}" -o "${ARCHIVE_PATH}"

rm -rf "${INSTALL_DIR}"
mkdir -p "${INSTALL_DIR}"
tar -C "${INSTALL_DIR}" --strip-components=1 -xzf "${ARCHIVE_PATH}"

ENV_FILE="${SCRIPT_DIR}/go_env.sh"
cat > "${ENV_FILE}" <<EOF
# Auto-generated by scripts/install_go.sh
export GOROOT="${INSTALL_DIR}"
export PATH="\${GOROOT}/bin:\${PATH}"
EOF

chmod +x "${ENV_FILE}"

echo ""
echo "Go installed successfully."
echo "To use it in this shell:"
echo "  source ${ENV_FILE}"
echo ""
echo "If you want this permanently, add to your shell profile:"
echo "  source ${ENV_FILE}"
